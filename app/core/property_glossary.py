PROPERTY_GLOSSARY: dict[str, PropertyGlossaryEntry] = {
    e.canonical_key.casefold(): e for e in _GLOSSARY_ENTRIES
}
BUILTIN_PROPERTY_GLOSSARY = PROPERTY_GLOSSARY


def get_property_glossary_entry(key: str) -> Optional[PropertyGlossaryEntry]:
    """Retrieve glossary metadata for a canonical key, case-insensitively."""
    if not key:
        return None
    return PROPERTY_GLOSSARY.get(key.strip().casefold())


def get_property_display_label(
    key: str,
    lang: str = "zh-Hant",
    locale: str | None = None,
) -> str:
    """Format human-readable presentation label: e.g. 狀態 (status) in zh-Hant.

    For unknown/custom properties, safely returns the canonical key unchanged.
    """
    cleaned = key.strip()
    entry = get_property_glossary_entry(cleaned)
    if not entry:
        return cleaned

    effective_lang = locale or lang
    is_en = str(effective_lang).lower().startswith("en")
    label = entry.label_en if is_en else entry.label_zh
    if not label or label.strip() == entry.canonical_key:
        return entry.canonical_key
    return f"{label} ({entry.canonical_key})"



def export_glossary_catalog() -> dict[str, dict[str, Any]]:
    """Export all glossary entries as a dict for API delivery to the client UI."""
    return {k: e.to_dict() for k, e in PROPERTY_GLOSSARY.items()}

