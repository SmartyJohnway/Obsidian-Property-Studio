"""Property Display Metadata & Glossary Layer.

Provides local-only, deterministic human-readable labels, descriptions,
and usage guidance for known Obsidian YAML frontmatter properties.

Core Safety Rules:
- Canonical YAML Property Keys remain completely untouched and un-translated in
  the storage/engine layer (e.g. status, owner, due_date).
- Display labels are presentation-only: 狀態 (status) in zh-Hant, Status (status) in en.
- Unknown/custom properties safely fallback to canonical key without speculative AI guesses.
- Never used to enforce schemas; purely informative for human understanding.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any, Optional


@dataclass(frozen=True)
class PropertyGlossaryEntry:
    canonical_key: str
    label_zh: str
    label_en: str
    short_description_zh: str
    short_description_en: str
    long_description_zh: str
    long_description_en: str
    usage_hint_zh: str
    usage_hint_en: str
    typical_type: str
    typical_control: str
    examples: tuple[str, ...] = field(default_factory=tuple)

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["examples"] = list(self.examples)
        return d


